@dataclasses.dataclass(frozen=True)
class RampSpec:
    """A ramp system given by its scalar ramp factors.

    ``nu``/``theta``/``h`` are ``dim x dim`` tables indexed ``[target][source]``:
    entry ``[k][n]`` holds the parameters of the ramp ``r_{k,n}(x_n)`` appearing
    in ``dot x_k``, or ``None`` when node ``n`` does not regulate node ``k``.

    This is the layout ``DSGRN_utils.WallLabelling.ramp_system_wall_labelling``
    expects, and it makes ``K(n) = sum_{m in target(n)} J_{m,n}``
    (``rem:K(n)``, RampSystemsv4.tex:254) a column sum.

    ``logic`` carries the interaction structure of ``def:interaction_function``:
    ``logic[k]`` is a list of factors, each a list of source indices, and

        E_k(x) = prod_factors ( sum_{n in factor} r_{k,n}(x_n) ).

    ``None`` means the type-I (single additive factor) reading, which is what
    both directly specified systems in the monograph use.
    """

    name: str
    source: str
    gamma: tuple[float, ...]
    nu: tuple[tuple[tuple[float, ...] | None, ...], ...]
    theta: tuple[tuple[tuple[float, ...] | None, ...], ...]
    h: tuple[tuple[tuple[float, ...] | None, ...], ...]
    #: Index set I claimed in the text, as tuples of allowed coordinates.
    claimed_index_set: tuple[int, ...] | None = None
    #: Interaction structure per node; None means one additive factor.
    logic: tuple[tuple[tuple[int, ...], ...], ...] | None = None

    @property
    def dim(self) -> int:
        return len(self.gamma)

    def _tables(self):
        """Empty lists in place of ``None`` for the DSGRN_utils entry point."""
        blank = lambda t: [[list(e) if e else [] for e in row] for row in t]
        return blank(self.nu), blank(self.theta), blank(self.h)

    def production(self, x):
        """``E(x)``: the interaction term, without the decay ``-gamma x``."""
        nu, theta, h = self._tables()

        def factor_sum(k, sources):
            return sum(
                ramp_function(x[n], nu[k][n], theta[k][n], h[k][n])
                for n in sources
                if theta[k][n]
            )

        out = []
        for k in range(self.dim):
            if self.logic is None:
                out.append(factor_sum(k, range(self.dim)))
                continue
            value = 1.0
            for factor in self.logic[k]:
                value *= factor_sum(k, factor)
            out.append(value)
        return out

    @classmethod
    def from_dsgrn(cls, network, parameter, h_bar: float, *, name: str = "", source: str = ""):
        """Build a ramp system realising a DSGRN parameter (``defn:DSGRN_ramp``).

        RampSystemsv4.tex:955-970: replace each switching function by a type-1
        ramp with the same plateaus --- ``nu = (l, l + delta)`` for activation and
        ``(l + delta, l)`` for repression --- keeping the DSGRN thresholds, and
        take ``gamma_n = 1`` as DSGRN normalises.

        A concrete point of the semi-algebraic region ``R(k)`` is drawn with
        ``DSGRN.ParameterSampler``.  ``prop:DSGRN_wall_constant`` says the induced
        wall labelling is constant on ``R(k) x H_0``, so any point of the region
        gives the same combinatorics; :func:`realises_dsgrn_labelling` checks
        that on the sample actually drawn.
        """
        import json as _json

        import DSGRN as _DSGRN

        sample = _json.loads(_DSGRN.ParameterSampler(network).sample(parameter))
        values = sample["Parameter"]
        dim = network.size()
        label = {k: network.name(k) for k in range(dim)}

        nu = [[None] * dim for _ in range(dim)]
        theta = [[None] * dim for _ in range(dim)]
        h = [[None] * dim for _ in range(dim)]
        for target in range(dim):
            for src in network.inputs(target):
                key = f"[{label[src]}->{label[target]}]"
                low = values["L" + key]
                high = values["U" + key]
                activating = network.interaction(src, target)
                nu[target][src] = (low, high) if activating else (high, low)
                theta[target][src] = (values["T" + key],)
                h[target][src] = (h_bar,)

        logic = tuple(
            tuple(tuple(factor) for factor in network.logic(k)) for k in range(dim)
        )
        return cls(
            name=name or f"dsgrn:{network.specification().strip()[:24]}",
            source=source,
            gamma=tuple(1.0 for _ in range(dim)),
            nu=tuple(tuple(row) for row in nu),
            theta=tuple(tuple(row) for row in theta),
            h=tuple(tuple(row) for row in h),
            logic=logic,
        )

    def vector_field(self, x):
        """``F_n(x) = -gamma_n x_n + E_n(x)`` (``defn:ramp_system``)."""
        e = self.production(x)
        return [-self.gamma[n] * x[n] + e[n] for n in range(self.dim)]

    @property
    def max_production(self) -> list[float]:
        """``M^E_n = max E_n``, respecting the interaction structure.

        Every ramp plateau is positive, so each factor sum is maximised
        independently and

            max E_n = prod_factors ( sum_{m in factor} max nu_{n,m} ).

        Summing the plateaus regardless of structure would be wrong for a
        type-II (product) interaction such as ``2 : (~1) 2``.
        """
        nu, theta, _h = self._tables()

        def factor_max(n, sources):
            return sum(max(nu[n][m]) for m in sources if theta[n][m])

        out = []
        for n in range(self.dim):
            if self.logic is None:
                out.append(factor_max(n, range(self.dim)))
                continue
            value = 1.0
            for factor in self.logic[n]:
                value *= factor_max(n, factor)
            out.append(value)
        return out

    @property
    def global_bound(self) -> list[float]:
        """``GB_n``, the outer sentinel threshold of ``defn:ramp-wall-labeling``.

        ``eq:GAB``: ``GB_n = max{ M^E_n / gamma_n, max ramp endpoint in n } + 1``.
        Note the two index roles: ``M^E_n`` is built from the ramps feeding node
        ``n`` (row ``n`` of the tables), while the ramp endpoints are those of
        the ramps *driven by* ``n`` (column ``n``), since those are the
        thresholds lying on the ``x_n`` axis.
        """
        _nu, theta, h = self._tables()
        production = self.max_production
        out = []
        for n in range(self.dim):
            endpoints = [
                t + hh
                for k in range(self.dim)
                for t, hh in zip(theta[k][n], h[k][n])
            ]
            out.append(
                max(production[n] / self.gamma[n], max(endpoints, default=0.0)) + 1.0
            )
        return out

    def wall_labelling(self, *, legacy: bool = False):
        """``(labelling, num_thresholds)`` via ``defn:ramp-wall-labeling``.

        The outer sentinel is ``GB_n``, as the definition states.  ``legacy=True``
        restores the ``theta + 10 h`` surrogate, which is h-dependent and loses
        strong dissipativity for small ``h``.
        """
        _nu, theta, h = self._tables()
        return ramp_system_wall_labelling(
            list(self.gamma),
            theta,
            h,
            self.production,
            global_bound=None if legacy else self.global_bound,
        )

    @property
    def num_thresholds(self) -> list[int]:
        """``K(n)``: the number of output thresholds of node ``n``."""
        _nu, theta, _h = self._tables()
        return [sum(len(theta[k][n]) for k in range(self.dim)) for n in range(self.dim)]

    @property
    def index_set(self) -> tuple[int, ...]:
        """``I = prod {0, ..., K(n)+1}``, reported as the top index per coordinate."""
        return tuple(k + 1 for k in self.num_thresholds)

    def with_uniform_width(self, h_bar: float) -> "RampSpec":
        """The same system with every half-width replaced by ``h_bar``.

        ``prop:smallh`` (RampSystemsv4.tex:624) proves nonemptiness of the
        width classes by exhibiting exactly such a uniform ``h``, and
        ``prop:wall-labeling-const`` (:490) says the wall labelling does not
        change with ``h`` inside ``H_0``.
        """
        scaled = tuple(
            tuple(tuple(h_bar for _ in e) if e else None for e in row) for row in self.h
        )
        return dataclasses.replace(
            self, name=f"{self.name}@h={h_bar:g}", h=scaled, claimed_index_set=None
        )


