def realises_dsgrn_labelling(name: str, index: int, h_bar: float, *, attempts: int = 6):
    """Build a ramp system for a DSGRN parameter and check it induces its labelling.

    ``prop:DSGRN_wall_constant`` (RampSystemsv4.tex:975) asserts the ramp induced
    wall labelling is constant on ``R(k) x H_0``, and in particular equals the
    one DSGRN computes combinatorially.  Returns ``(spec, matches)`` for the
    first sample whose labelling matches, or the last one tried.
    """
    import DSGRN

    net = network(name)
    par = parameter(name, index)
    # CubicalBlowupGraph rebuilds the network without self-edge blowup; the
    # combinatorial labelling to compare against is the one it uses.
    plain = DSGRN.Network(net.specification(), edge_blowup="none")
    plain_graph = DSGRN.ParameterGraph(plain)
    target = plain_graph.parameter(index).labelling()

    spec = None
    for _ in range(attempts):
        spec = RampSpec.from_dsgrn(net, par, h_bar,
                                   name=f"{name}[{index}]",
                                   source=f"DSGRN {name} node {index}")
        # The sampler draws thresholds anywhere in the region, so a fixed
        # half-width can overlap two windows and violate admissibility.  Shrink
        # it to a quarter of the smallest threshold gap on each axis.
        spec = spec.with_uniform_width(min(h_bar, 0.25 * _smallest_threshold_gap(spec)))
        try:
            labelling, _K = spec.wall_labelling()
        except ValueError:
            continue
        if labelling == target:
            return spec, True
    return spec, False


def _smallest_threshold_gap(spec: "RampSpec") -> float:
    """Smallest distance between consecutive output thresholds, over all axes."""
    _nu, theta, _h = spec._tables()
    best = float("inf")
    for n in range(spec.dim):
        pooled = sorted(t for k in range(spec.dim) for t in theta[k][n])
        best = min([best] + [b - a for a, b in zip(pooled, pooled[1:])])
        if pooled:
            best = min(best, pooled[0])  # keep the first window clear of 0
    return best if best != float("inf") else 1.0
